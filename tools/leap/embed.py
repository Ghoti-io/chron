TEMPLATE = LICENSE_NOTICE + "\n" + '''/**
 * @file
 *
 * The leap-second table compiled into this library.
 *
 * GENERATED by tools/leap/embed.py from %(source)s
 * (last updated %(generated_from)s). Do not edit: regenerate it.
 *
 * This table **expires on %(expiry_iso)s**, which is the expiry the source
 * file carried. Past that date every conversion through it reports
 * GCHRON_ERR_EXPIRED rather than assuming no further leap second was issued.
 * A binary built years ago must not answer confidently about a year it could
 * not have known about (design.md section 5.1 item 3).
 */

#include <ghoti.io/chron/leap.h>
#include <ghoti.io/chron/macros.h>

#include "leap_internal.h"

/** Every leap second issued as of the source file above. */
static const GCHRON_LeapEntry BUILTIN_ENTRIES[] = {
%(rows)s
};

static const GCHRON_LeapTable BUILTIN_TABLE = {
  NULL,                      /* allocator: nothing here is owned */
  BUILTIN_ENTRIES,
  %(count)d,
  INT64_C(%(expiry_unix)d),  /* expires %(expiry_iso)s */
  INT64_C(%(updated_unix)d),
  true
};

const GCHRON_LeapTable * gchron_leap_table_builtin(void) {
  return &BUILTIN_TABLE;
}
'''


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", nargs="?", default=None)
    parser.add_argument("-o", "--output", default="src/leap/leap_builtin.c")
    # How the generated comment names the source. MSYS2 rewrites a POSIX path
    # argument for a native Python - /usr/share/zoneinfo/... arrives as
    # C:/msys64/usr/share/zoneinfo/... - so the path this script opened is not
    # the spelling the committed file records, and check-generated would call
    # an unchanged table stale. The Makefile passes the POSIX spelling here.
    parser.add_argument("--source-name", default=None)
    args = parser.parse_args()

    source = args.source
    if source is not None:
        if not os.path.exists(source):
            raise SystemExit("no such file: %s" % source)
    else:
        for candidate in DEFAULT_SOURCES:
            if candidate and os.path.exists(candidate):
                source = candidate
                break
        if source is None:
            raise SystemExit(
                "no leap-seconds.list found. Looked in: %s\n"
                "Pass one explicitly, or fetch it from\n"
                "  https://data.iana.org/time-zones/tzdb/leap-seconds.list"
                % ", ".join(c for c in DEFAULT_SOURCES if c))

    text = pathlib.Path(source).read_text(encoding="utf-8", errors="replace")
    entries, updated, expiry = parse(text)

    output = pathlib.Path(args.output)
    output.parent.mkdir(parents=True, exist_ok=True)
    # LF line endings: the file is committed and compared byte for byte, and a
    # native Python on Windows would otherwise write CRLF.
    output.write_text(render(entries, updated, expiry, args.source_name or source),
                      newline="\n")

    print("%s: %d entries, expires %s"
          % (args.output, len(entries), iso(expiry)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
