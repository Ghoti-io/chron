#!/usr/bin/env python3
"""Generate src/leap/leap_builtin.c from a leap-seconds.list.

The built-in table is a fallback for a machine that has no copy of the file.
It is generated, never edited, and this script **fails rather than writing a
placeholder** (CONVENTIONS.md section 6): a table of zero leap seconds would
answer every conversion wrongly and look like it was working.

The expiry is copied from the source file rather than invented, so a binary
built from an old file reports GCHRON_ERR_EXPIRED instead of pretending its
knowledge is current. That is the point of design.md section 5.1 item 3.

Usage:
    tools/leap/embed.py [source] [-o output]

`source` defaults to $TZDIR/leap-seconds.list or
/usr/share/zoneinfo/leap-seconds.list.
"""

import argparse
import datetime
import os
import pathlib
import sys

NTP_TO_UNIX = 2208988800

DEFAULT_SOURCES = [
    os.path.join(os.environ["TZDIR"], "leap-seconds.list")
    if os.environ.get("TZDIR") else None,
    "/usr/share/zoneinfo/leap-seconds.list",
    "/usr/share/zoneinfo-leaps/leap-seconds.list",
]


def parse(text):
    """Return (entries, updated_ntp, expiry_ntp).

    entries is a list of (ntp, offset). The parse is deliberately strict:
    this runs at build time, where a malformed file must stop the build
    rather than silently produce a shorter table.
    """
    entries = []
    updated = None
    expiry = None

    for number, raw in enumerate(text.splitlines(), start=1):
        line = raw.strip()
        if not line:
            continue
        if line.startswith("#"):
            if line.startswith("#$"):
                updated = int(line[2:].strip())
            elif line.startswith("#@"):
                expiry = int(line[2:].strip())
            continue
        # Data: <ntp> <offset> [# comment]
        body = line.split("#", 1)[0].split()
        if len(body) < 2:
            raise SystemExit("line %d: expected an NTP time and an offset: %r"
                             % (number, raw))
        entries.append((int(body[0]), int(body[1])))

    if not entries:
        raise SystemExit("no leap-second entries in the source file")
    if expiry is None:
        raise SystemExit("the source file carries no #@ expiry line")
    if entries != sorted(entries):
        raise SystemExit("the source file's entries are not in time order")
    return entries, updated, expiry


def iso(ntp):
    """An NTP timestamp as a readable UTC date, for the generated comments."""
    moment = datetime.datetime(1970, 1, 1, tzinfo=datetime.timezone.utc) \
        + datetime.timedelta(seconds=ntp - NTP_TO_UNIX)
    return moment.strftime("%Y-%m-%d")


def render(entries, updated, expiry, source):
    rows = []
    previous = None
    for ntp, offset in entries:
        unix = ntp - NTP_TO_UNIX
        if previous is None:
            note = "UTC becomes a stepped scale"
        elif offset > previous:
            note = "+1s at the end of the previous day"
        elif offset < previous:
            note = "-1s at the end of the previous day (negative leap)"
        else:
            note = "no change"
        negative = "true" if previous is not None and offset < previous \
            else "false"
        rows.append(
            "  { { INT64_C(%d), 0 }, %d, %s },  /* %s  %s */"
            % (unix, offset, negative, iso(ntp), note))
        previous = offset

    return TEMPLATE % {
        "source": source,
        "generated_from": iso(updated) if updated else "unknown",
        "expiry_iso": iso(expiry),
        "rows": "\n".join(rows),
        "count": len(entries),
        "expiry_unix": expiry - NTP_TO_UNIX,
        "updated_unix": (updated - NTP_TO_UNIX) if updated
        else (entries[-1][0] - NTP_TO_UNIX),
    }


